"""Servizio di dominio per il ripristino ed la sanificazione dell'SQL per PostgreSQL.

:author: Riccardo Morabito
"""

from re import DOTALL, IGNORECASE, MULTILINE, Match, compile as re_compile

_RE_MARKDOWN_BLOCK = re_compile(r"```(?:sql|postgres)?\s*(.*?)\s*```", flags=DOTALL | IGNORECASE)
_RE_MARKDOWN_PREFIX = re_compile(r"^```[a-zA-Z]*\n?")
_RE_MARKDOWN_SUFFIX = re_compile(r"\n?```$")
_RE_ESCAPED_QUOTES = re_compile(r"(?<=\w)\\'(?=\w)")
_RE_IDENTITY = re_compile(r"GENERATED\s+ALWAYS\s+AS\s+IDENTITY", flags=IGNORECASE)
_RE_TRAILING_COMMAS = re_compile(
    r",\s*(\)|FROM\b|WHERE\b|GROUP\s+BY\b|ORDER\s+BY\b|HAVING\b)", flags=IGNORECASE
)
_RE_HYPHENATED_IDENTIFIER = re_compile(
    r"('(?:''|[^'])*')|\b([a-zA-Z][a-zA-Z0-9_]*)-([a-zA-Z][a-zA-Z0-9_]*)\b"
)
_RE_GENERATED_SUBQUERY = re_compile(
    r"GENERATED\s+ALWAYS\s+AS\s*\(.*?SELECT.*?\)\s*STORED", flags=IGNORECASE | DOTALL
)
_RE_GENERATED_CURRENT = re_compile(
    r"GENERATED\s+ALWAYS\s+AS\s*\(.*?CURRENT_(?:DATE|TIMESTAMP|TIME).*?\)\s*STORED",
    flags=IGNORECASE | DOTALL,
)
_RE_GENERATED_NOW = re_compile(
    r"GENERATED\s+ALWAYS\s+AS\s*\(.*?NOW\s*\(\).*?\)\s*STORED", flags=IGNORECASE | DOTALL
)
_RE_DOUBLE_PAREN_STORED = re_compile(r"\){4,}\s*STORED", flags=IGNORECASE)
_RE_STRAY_COLUMN_STMT = re_compile(r"^\s*Column\.?\s*;?\s*$", flags=IGNORECASE | MULTILINE)
_RE_CREATE_TABLE_NAME = re_compile(
    r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?\"?([a-zA-Z_][a-zA-Z0-9_]*)\"?", flags=IGNORECASE
)


class PostgresSQLRepair:
    """Servizio di dominio per il ripristino ed la sanificazione dell'SQL generato da LLM."""

    def repair(self, sql_text: str) -> str:
        """Applica la pipeline di riparazione deterministica al testo SQL per PostgreSQL."""
        if not sql_text:
            return ""

        sql = sql_text.strip()
        sql = self._strip_markdown_fences(sql)
        sql = self._fix_escaped_quotes(sql)
        sql = self._fix_identity_columns(sql)
        sql = self._fix_generated_subquery(sql)
        sql = self._fix_generated_current(sql)
        sql = self._fix_double_paren_stored(sql)
        sql = self._fix_stray_column_stmt(sql)
        sql = self._dedupe_create_table(sql)
        sql = self._fix_trailing_commas(sql)
        sql = self._fix_hyphenated_identifiers(sql)
        sql = self._ensure_semicolon(sql)
        return sql.strip()

    def _strip_markdown_fences(self, sql: str) -> str:
        """Rimuove eventuali involucri di codice Markdown."""
        if "```" in sql:
            m = _RE_MARKDOWN_BLOCK.search(sql)
            if m:
                return m.group(1).strip()
            sql = _RE_MARKDOWN_PREFIX.sub("", sql)
            sql = _RE_MARKDOWN_SUFFIX.sub("", sql).strip()
        return sql

    def _fix_escaped_quotes(self, sql: str) -> str:
        r"""Converte l'escape errato C/JS (\') nel raddoppio apici Postgres ('')."""
        return _RE_ESCAPED_QUOTES.sub("''", sql)

    def _fix_identity_columns(self, sql: str) -> str:
        """Converte GENERATED ALWAYS AS IDENTITY in GENERATED BY DEFAULT AS IDENTITY."""
        return _RE_IDENTITY.sub("GENERATED BY DEFAULT AS IDENTITY", sql)

    def _fix_trailing_commas(self, sql: str) -> str:
        """Rimuove le virgole pendenti prima di chiusura parentesi o clausole principali."""
        return _RE_TRAILING_COMMAS.sub(r" \1", sql)

    def _fix_hyphenated_identifiers(self, sql: str) -> str:
        """Sostituisce i trattini negli identificatori SQL non virgolettati con underscore."""
        return _RE_HYPHENATED_IDENTIFIER.sub(self._replace_hyphenated_match, sql)

    @staticmethod
    def _replace_hyphenated_match(match: Match[str]) -> str:
        """Sostituisce il trattino con underscore se il match e' un identificatore."""
        if match.group(1):
            return match.group(1)
        return f"{match.group(2)}_{match.group(3)}"

    def _fix_generated_subquery(self, sql: str) -> str:
        """Rimuove GENERATED con subquery SELECT (non ammessa da Postgres)."""
        return _RE_GENERATED_SUBQUERY.sub("", sql)

    def _fix_generated_current(self, sql: str) -> str:
        """Rimuove GENERATED con CURRENT_DATE/TIMESTAMP o NOW() (non immutable)."""
        sql = _RE_GENERATED_CURRENT.sub("", sql)
        return _RE_GENERATED_NOW.sub("", sql)

    def _fix_double_paren_stored(self, sql: str) -> str:
        """Corregge parentesi extra prima di STORED (conservativo)."""
        return re_compile(r"\){4,}\s*STORED", flags=IGNORECASE).sub("))) STORED", sql)

    def _fix_stray_column_stmt(self, sql: str) -> str:
        """Rimuove statement spuri tipo 'Column.' generati dall'LLM."""
        lines = []
        for line in sql.splitlines():
            if _RE_STRAY_COLUMN_STMT.match(line):
                continue
            lines.append(line)
        return "\n".join(lines)

    def _dedupe_create_table(self, sql: str) -> str:
        """Rimuove definizioni duplicate della stessa tabella (mantiene la prima)."""
        seen: set[str] = set()
        parts = sql.split(";")
        kept: list[str] = []
        for part in parts:
            stripped = part.strip()
            if not stripped:
                continue
            m = _RE_CREATE_TABLE_NAME.search(stripped)
            if m:
                name = m.group(1).lower()
                if name in seen:
                    continue
                seen.add(name)
            kept.append(part)
        if len(kept) == len(parts):
            return sql
        return ";".join(kept) + (";" if sql.strip().endswith(";") else "")

    def _ensure_semicolon(self, sql: str) -> str:
        """Assicura che il comando o script SQL termini con punto e virgola ';'."""
        cleaned = sql.rstrip()
        if cleaned and not cleaned.endswith(";"):
            return f"{cleaned};"
        return cleaned
